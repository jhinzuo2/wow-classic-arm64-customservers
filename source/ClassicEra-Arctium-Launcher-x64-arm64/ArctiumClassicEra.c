typedef struct { size_t off; uint8_t len; uint8_t b[8]; } Patch;
typedef struct { Patch *v; size_t n, cap; } PatchList;

static int pl_add(PatchList *l, size_t off, const uint8_t *b, size_t len) {
    if (len > 8) return 0;
    if (l->n == l->cap) {
        size_t nc = l->cap ? l->cap * 2 : 256;
        Patch *nv = (Patch *)realloc(l->v, nc * sizeof(Patch));
        if (!nv) return 0;
        l->v = nv; l->cap = nc;
    }
    Patch *p = &l->v[l->n++];
    p->off = off; p->len = (uint8_t)len; memcpy(p->b, b, len);
    return 1;
}
static uint32_t rd32(const uint8_t *p) { return (uint32_t)p[0] | ((uint32_t)p[1] << 8) | ((uint32_t)p[2] << 16) | ((uint32_t)p[3] << 24); }
static void wr32(uint8_t *p, uint32_t v) { p[0] = (uint8_t)v; p[1] = (uint8_t)(v >> 8); p[2] = (uint8_t)(v >> 16); p[3] = (uint8_t)(v >> 24); }

/* First match of a pattern (negative entries are wildcards) at or after 'start'; SIZE_MAX if none. */
static size_t find_pat(const uint8_t *d, size_t n, const int16_t *p, size_t pl, size_t start) {
    if (pl == 0 || n < pl || start > n - pl) return SIZE_MAX;
    size_t last = n - pl;
    for (size_t i = start; i <= last; i++) {
        if (p[0] >= 0) {
            const uint8_t *q = (const uint8_t *)memchr(d + i, (int)p[0], last - i + 1);
            if (!q) return SIZE_MAX;
            i = (size_t)(q - d);
        }
        size_t m = 1;
        while (m < pl && (p[m] < 0 || d[i + m] == (uint8_t)p[m])) m++;
        if (m == pl) return i;
    }
    return SIZE_MAX;
}
/* All non-overlapping matches (like Arctium: continue after the end of a match). Returns the total count and
   stores up to 'max' offsets in out (out may be NULL). */
static size_t find_all_pat(const uint8_t *d, size_t n, const int16_t *p, size_t pl, size_t *out, size_t max) {
    size_t c = 0, pos = 0;
    for (;;) {
        size_t m = find_pat(d, n, p, pl, pos);
        if (m == SIZE_MAX) break;
        if (out && c < max) out[c] = m;
        c++;
        pos = m + pl;
    }
    return c;
}
static size_t str_to_pat(const char *s, size_t len, int16_t *out) {
    for (size_t i = 0; i < len; i++) out[i] = (int16_t)(uint8_t)s[i];
    return len;
}

/* Integrity-check functions: replace the first bytes by "ret 0". */
static size_t collect_integrity(const uint8_t *d, size_t n, PatchList *out, size_t *nFound) {
    static const uint8_t RET0[3] = { 0xC2, 0x00, 0x00 };
    size_t total = 0;
    const int16_t *pats[2] = { P_INTEGRITY, P_INTEGRITY2 };
    const size_t lens[2] = { sizeof P_INTEGRITY / sizeof P_INTEGRITY[0], sizeof P_INTEGRITY2 / sizeof P_INTEGRITY2[0] };
    for (int k = 0; k < 2; k++) {
        size_t cnt = find_all_pat(d, n, pats[k], lens[k], NULL, 0);
        size_t *offs = (size_t *)malloc((cnt ? cnt : 1) * sizeof(size_t));
        if (!offs) return total;
        find_all_pat(d, n, pats[k], lens[k], offs, cnt);
        for (size_t i = 0; i < cnt; i++) { if (pl_add(out, offs[i], RET0, 3)) total++; }
        free(offs);
        if (nFound) nFound[k] = cnt;
    }
    return total;
}

typedef struct { int64_t target; size_t minpos; } RemapTarget;
static int rt_cmp(const void *a, const void *b) {
    const RemapTarget *x = (const RemapTarget *)a, *y = (const RemapTarget *)b;
    return x->target < y->target ? -1 : x->target > y->target ? 1 : 0;
}
static int rt_hit(const RemapTarget *rt, size_t nrt, int64_t t, size_t pos) {
    size_t lo = 0, hi = nrt;
    while (lo < hi) { size_t mid = (lo + hi) / 2; if (rt[mid].target < t) lo = mid + 1; else hi = mid; }
    for (; lo < nrt && rt[lo].target == t; lo++) if (rt[lo].minpos <= pos) return 1;
    return 0;
}
typedef struct { size_t matches, usable, skippedUncond, bad, longJumps, shortJumps; } RemapStats;

/* The client's "remap" checks end in a conditional jump (jae) to the real code. Arctium finds every other
   conditional jump that goes to the same target and turns it into an unconditional one:
     0F 8x rel32  ->  E9 (rel32+1)       (5 bytes written)
     7x rel8 (preceded by a 48-prefixed test, 3 bytes before)  ->  EB
   Arctium scans the whole image once per remap match (from the previous match onward); this does the same in a
   single pass over the image. */
static int analyze_remap(const uint8_t *d, size_t n, PatchList *out, RemapStats *st) {
    memset(st, 0, sizeof *st);
    size_t cnt = find_all_pat(d, n, P_REMAP, sizeof P_REMAP / sizeof P_REMAP[0], NULL, 0);
    st->matches = cnt;
    if (cnt == 0) return 1;
    size_t *ms = (size_t *)malloc(cnt * sizeof(size_t));
    RemapTarget *rt = (RemapTarget *)malloc(cnt * sizeof(RemapTarget));
    if (!ms || !rt) { free(ms); free(rt); return 0; }
    find_all_pat(d, n, P_REMAP, sizeof P_REMAP / sizeof P_REMAP[0], ms, cnt);
    size_t nrt = 0, lastAddr = 0;
    for (size_t k = 0; k < cnt; k++) {
        size_t a = ms[k];
        if (a + 4 + 6 > n) { st->bad++; continue; }
        const uint8_t *ins = d + a + 4;
        int64_t operand;
        if (ins[0] == 0xE9 || ins[0] == 0xEB) { st->skippedUncond++; continue; }
        if (ins[0] >= 0x70 && ins[0] < 0x7F) operand = (int64_t)ins[1] + 2;
        else if (ins[0] == 0x0F && ins[1] >= 0x80 && ins[1] <= 0x8F) operand = (int64_t)(int32_t)rd32(ins + 2) + 6;
        else { st->bad++; continue; }
        rt[nrt].target = (int64_t)a + operand + 4;
        rt[nrt].minpos = lastAddr;
        nrt++;
        lastAddr = a;
    }
    st->usable = nrt;
    if (nrt) {
        qsort(rt, nrt, sizeof(RemapTarget), rt_cmp);
        for (size_t i = 0; i + 1 < n; i++) {
            uint8_t c = d[i];
            if (c == 0x0F) {
                if (d[i + 1] >= 0x80 && d[i + 1] <= 0x8F && i + 6 <= n) {
                    int32_t rel = (int32_t)rd32(d + i + 2);
                    int64_t t = (int64_t)i + 6 + rel;
                    if (rt_hit(rt, nrt, t, i)) {
                        uint8_t b[5]; b[0] = 0xE9; wr32(b + 1, (uint32_t)(rel + 1));
                        if (pl_add(out, i, b, 5)) st->longJumps++;
                    }
                }
            } else if (c >= 0x70 && c < 0x7F) {
                if (i >= 3 && d[i - 3] == 0x48) {
                    int64_t t = (int64_t)i + 2 + d[i + 1];
                    if (rt_hit(rt, nrt, t, i)) {
                        uint8_t b = 0xEB;
                        if (pl_add(out, i, &b, 1)) st->shortJumps++;
                    }
                }
            }
        }
    }
    free(ms); free(rt);
    return 1;
}

static int b64val(int c) {
    if (c >= 'A' && c <= 'Z') return c - 'A';
    if (c >= 'a' && c <= 'z') return c - 'a' + 26;
    if (c >= '0' && c <= '9') return c - '0' + 52;
    if (c == '+') return 62;
    if (c == '/') return 63;
    return -1;
}
static uint8_t *b64_decode(const char *s, size_t *outLen) {
    size_t n = strlen(s);
    uint8_t *o = (uint8_t *)malloc(n / 4 * 3 + 4);
    if (!o) return NULL;
    size_t k = 0; uint32_t acc = 0; int bits = 0;
    for (size_t i = 0; i < n; i++) {
        if (s[i] == '=') break;
        int v = b64val((unsigned char)s[i]);
        if (v < 0) continue;
        acc = (acc << 6) | (uint32_t)v; bits += 6;
        if (bits >= 8) { bits -= 8; o[k++] = (uint8_t)(acc >> bits); acc &= (1u << bits) - 1; }
    }
    *outLen = k;
    return o;
}
static int pe_parse(const uint8_t *h, size_t n, uint16_t *machine, uint32_t *sizeOfImage) {
    if (n < 0x40 || h[0] != 'M' || h[1] != 'Z') return 0;
    uint32_t e = rd32(h + 0x3C);
    if ((size_t)e + 0x58 > n || memcmp(h + e, "PE\0\0", 4) != 0) return 0;
    *machine = (uint16_t)(h[e + 4] | (h[e + 5] << 8));
    *sizeOfImage = rd32(h + e + 24 + 56);
    return 1;
}

/* ---- ARM64 (A64) helpers: scan the decrypted ARM64 code for the equivalents of the x64 cert-check sites ---- */
#define A64_NOP 0xD503201Fu
typedef struct { size_t idx; int kind; int exact; uint32_t oldWord; uint32_t newWord; size_t patchIdx; } A64Hit;

static int a64_is_ret(uint32_t w) { return w == 0xD65F03C0u; }
/* conditional branches with a PC-relative target: b.cond, cbz/cbnz, tbz/tbnz. Returns 1 and the target word index. */
static int a64_cond_target(uint32_t w, size_t at, int64_t *tgt) {
    int64_t imm;
    if ((w & 0xFF000010u) == 0x54000000u || (w & 0x7E000000u) == 0x34000000u) {       /* imm19 at bits 5..23 */
        imm = (w >> 5) & 0x7FFFF; if (imm & 0x40000) imm -= 0x80000;
    } else if ((w & 0x7E000000u) == 0x36000000u) {                                     /* tbz/tbnz: imm14 at bits 5..18 */
        imm = (w >> 5) & 0x3FFF; if (imm & 0x2000) imm -= 0x4000;
    } else return 0;
    *tgt = (int64_t)at + imm;
    return 1;
}
/* any instruction that changes control flow (used to keep the "early return" block straight-line) */
static int a64_is_flow(uint32_t w) {
    int64_t t;
    if (a64_cond_target(w, 0, &t)) return 1;
    if ((w & 0x7C000000u) == 0x14000000u) return 1;      /* b / bl */
    if ((w & 0xFE000000u) == 0xD6000000u) return 1;      /* br / blr / ret / eret */
    return 0;
}
static int a64_is_cmp_w_imm(uint32_t w, uint32_t v) { return (w & 0xFFC0001Fu) == 0x7100001Fu && ((w >> 10) & 0xFFFu) == v; }
static int a64_is_ldr_x_off60(uint32_t w) { return (w & 0xFFFFFC00u) == 0xF9403000u; }   /* ldr xT, [xN, #0x60] */

/* Site "CertBundle". The x64 pattern 75 06 48 83 C4 60 5F C3 is
 *     call f(0x148505, ...) ; test al,al ; jne +6 ; add rsp,60h ; pop rdi ; ret
 * i.e. "if (!f(...)) return;" and the patch (jne -> nop) forces the early return, so the check that follows is skipped.
 * (The ARM64 scanner used to look for "ldr xT,[xN,#0x60]"; that was a misreading of 48 83 C4 60 = add rsp,0x60.)
 * ARM64 analogue: movz wD,#0x8505 + movk wD,#0x14,lsl#16 (the 0x148505 argument), a call, then a test of the bool result:
 *     cbz / tbz  w0,#0  -> branch to the early-return block : patch = unconditional "b <same target>"
 *     cbnz / tbnz w0,#0 -> early-return block is inline     : patch = NOP (the inline block must reach a ret / b)
 * kind 1 = exact. */
static int a64_is_movz_w(uint32_t w, uint32_t imm, uint32_t *rd) { if ((w & 0xFFE0001Fu & ~0x1Fu) == 0x52800000u && ((w >> 5) & 0xFFFFu) == imm) { *rd = w & 31; return 1; } return 0; }
static int a64_is_movk16_w(uint32_t w, uint32_t imm, uint32_t *rd) { if ((w & 0xFFE00000u) == 0x72A00000u && ((w >> 5) & 0xFFFFu) == imm) { *rd = w & 31; return 1; } return 0; }
static int a64_is_call(uint32_t w) { return (w & 0xFC000000u) == 0x94000000u || (w & 0xFFFFFC1Fu) == 0xD63F0000u; }   /* bl | blr */
/* bool test of register r: returns 1 = branch taken when false (cbz/tbz), 2 = branch taken when true (cbnz/tbnz), 0 = no */
static int a64_bool_test(uint32_t w, uint32_t r) {
    if ((w & 0xFF00001Fu) == (0x34000000u | r)) return 1;                   /* cbz  wR */
    if ((w & 0xFF00001Fu) == (0x35000000u | r)) return 2;                   /* cbnz wR */
    if ((w & 0xFFF8001Fu) == (0x36000000u | r)) return 1;                   /* tbz  wR,#0 */
    if ((w & 0xFFF8001Fu) == (0x37000000u | r)) return 2;                   /* tbnz wR,#0 */
    return 0;
}
static size_t a64_scan_certbundle(const uint32_t *w, size_t n, A64Hit *out, size_t max) {
    size_t cnt = 0;
    for (size_t i = 12; i + 40 < n && cnt < max; i++) {
        uint32_t rd = 0, rk = 0;
        if (!a64_is_movz_w(w[i], 0x8505, &rd)) continue;
        size_t kpos = SIZE_MAX;
        for (size_t k = i - 12; k <= i + 12; k++) if (k != i && a64_is_movk16_w(w[k], 0x14, &rk) && rk == rd) { kpos = k; break; }
        if (kpos == SIZE_MAX) continue;
        size_t from = (kpos > i ? kpos : i) + 1, call = SIZE_MAX;
        for (size_t k = from; k < from + 20 && k < n; k++) {
            if (a64_is_call(w[k])) { call = k; break; }
            if (a64_is_ret(w[k])) break;
        }
        if (call == SIZE_MAX) continue;
        uint32_t tracked = 1u;                                               /* bit r set: register r holds the call result (bit 0) */
        for (size_t j = call + 1; j <= call + 8 && j < n; j++) {
            uint32_t x = w[j];
            int tk = 0, t0 = 0; uint32_t r;
            for (r = 0; r < 31; r++) if ((tracked >> r) & 1u) { tk = a64_bool_test(x, r); if (tk) { t0 = (int)r; break; } }
            if (tk) {
                int64_t t; a64_cond_target(x, j, &t);
                A64Hit *h = &out[cnt];
                memset(h, 0, sizeof *h);
                h->idx = j; h->kind = 1; h->exact = 1; h->oldWord = x; h->patchIdx = j; (void)t0;
                if (tk == 1) {                                               /* branch to the early return: make it unconditional */
                    int64_t d = t - (int64_t)j;
                    if (d < -(1 << 25) || d >= (1 << 25)) break;
                    h->newWord = 0x14000000u | ((uint32_t)d & 0x03FFFFFFu);
                } else {                                                     /* inline early return must follow: epilogue ... ret / b */
                    int ok = 0;
                    for (size_t k = j + 1; k <= j + 10 && k < n; k++) { if (a64_is_ret(w[k]) || (w[k] & 0xFC000000u) == 0x14000000u) { ok = 1; break; } if (a64_is_flow(w[k])) break; }
                    if (!ok) break;
                    h->newWord = A64_NOP;
                }
                cnt++;
                break;
            }
            if (a64_is_flow(x)) break;
            /* follow copies of the call result: mov wX,wR | uxtb wX,wR | and wX,wR,#1 (R tracked) */
            { uint32_t src = (x >> 5) & 31, dst = x & 31; int cp = 0;
              if ((x & 0xFFE0FFE0u) == 0x2A0003E0u) { src = (x >> 16) & 31; cp = 1; }           /* mov wD,wM (orr wD,wzr,wM) */
              else if ((x & 0xFFFFFC00u) == 0x53001C00u) cp = 1;                                  /* uxtb wD,wN */
              else if ((x & 0xFFFFFC00u) == 0x12000000u) cp = 1;                                  /* and wD,wN,#1 */
              if (cp && src < 31 && ((tracked >> src) & 1u) && dst < 31) tracked |= 1u << dst; }
        }
    }
    return cnt;
}

/* Site "CertCommonName". The x64 pattern 80 ?? 2A 75 ?? 32 C0 48 is the exit of a reverse scan loop
 *     cmp r11b,'*' ; jne <loop start (backwards)> ; xor al,al ; <epilogue> ; ret      -> patch: xor al,al -> mov al,1
 *   kind 1 = cmp wN,#0x2a ; (<=5 non-flow words) ; b.ne <backwards> ; mov wD,#0|wzr ; straight-line epilogue ; ret|b
 *            (exact analogue, patch = mov wD,#1)           [also accepted: the old forward form  b.ne +2 ; mov wD,#0]
 *   kind 2 = cmp wN,#0x2a ; csel wD,wzr,wM,eq              (report only)
 *   kind 3 = any other cmp wN,#0x2a                        (report only, context for manual work) */
static size_t a64_scan_commonname(const uint32_t *w, size_t n, A64Hit *out, size_t max, size_t *nAll) {
    size_t cnt = 0, all = 0;
    for (size_t i = 0; i + 4 < n; i++) {
        if (!a64_is_cmp_w_imm(w[i], 0x2A)) continue;
        all++;
        if (cnt >= max) continue;
        A64Hit *h = &out[cnt];
        memset(h, 0, sizeof *h);
        h->idx = i; h->kind = 3; h->oldWord = w[i]; h->patchIdx = i;
        for (size_t k = i + 1; k <= i + 6 && k + 1 < n; k++) {
            uint32_t x = w[k];
            if ((x & 0xFF00001Fu) == 0x54000001u) {                                   /* b.ne */
                int64_t t; a64_cond_target(x, k, &t);
                uint32_t y = w[k + 1];
                uint32_t rd = y & 31;
                int isMov0 = (y == (0x52800000u | rd)) || (y == (0x2A1F03E0u | rd));  /* mov wD,#0 | mov wD,wzr */
                if (isMov0 && t == (int64_t)k + 2) {                                  /* forward form */
                    h->kind = 1; h->exact = 1; h->patchIdx = k + 1; h->oldWord = y; h->newWord = 0x52800020u | rd;
                } else if (isMov0 && t < (int64_t)i) {                                /* loop form: must end in an epilogue */
                    int ok = 0;
                    for (size_t m = k + 2; m <= k + 12 && m < n; m++) {
                        if (a64_is_ret(w[m]) || (w[m] & 0xFC000000u) == 0x14000000u) { ok = 1; break; }
                        if (a64_is_flow(w[m])) break;
                    }
                    if (ok) { h->kind = 1; h->exact = 1; h->patchIdx = k + 1; h->oldWord = y; h->newWord = 0x52800020u | rd; }
                }
                break;
            }
            if ((x & 0xFFE0FFE0u) == 0x1A8003E0u) {      /* csel wD,wzr,wM,eq  (rn=31, cond=eq) */
                h->kind = 2; h->patchIdx = k; h->oldWord = x;
                break;
            }
            if (a64_is_flow(x)) break;
        }
        cnt++;
    }
    if (nAll) *nAll = all;
    return cnt;
}

/* "RVA:NEWHEX" or "RVA:OLDHEX>NEWHEX" -> numbers. hex may contain spaces. Returns 1 on success. */
static int hex_bytes(const char *s, size_t len, uint8_t *out, size_t max, size_t *outLen) {
    size_t n = 0; int hi = -1;
    for (size_t i = 0; i < len; i++) {
        int c = s[i], v;
        if (c == ' ' || c == '_') continue;
        if (c >= '0' && c <= '9') v = c - '0'; else if (c >= 'a' && c <= 'f') v = c - 'a' + 10; else if (c >= 'A' && c <= 'F') v = c - 'A' + 10; else return 0;
        if (hi < 0) hi = v; else { if (n >= max) return 0; out[n++] = (uint8_t)(hi * 16 + v); hi = -1; }
    }
    if (hi >= 0 || n == 0) return 0;
    *outLen = n; return 1;
}

/* .text location from the PE section table: rva, virtual size, raw file offset, raw size. */
static int pe_find_section(const uint8_t *h, size_t n, const char *name, uint32_t *rva, uint32_t *vsize, uint32_t *rawPtr, uint32_t *rawSize) {
    if (n < 0x40) return 0;
    uint32_t e = rd32(h + 0x3C);
    if ((size_t)e + 24 > n) return 0;
    unsigned ns = (unsigned)(h[e + 6] | (h[e + 7] << 8)), opt = (unsigned)(h[e + 20] | (h[e + 21] << 8));
    size_t s0 = (size_t)e + 24 + opt;
    for (unsigned i = 0; i < ns; i++) {
        size_t o = s0 + (size_t)i * 40;
        if (o + 40 > n) return 0;
        if (strncmp((const char *)h + o, name, 8) == 0) {
            *vsize = rd32(h + o + 8); *rva = rd32(h + o + 12); *rawSize = rd32(h + o + 16); *rawPtr = rd32(h + o + 20);
            return 1;
        }
    }
    return 0;
}
